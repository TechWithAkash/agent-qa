"""
S9: Pytest-Playwright Test Generator.
Section 10 of the Technical Architecture.
"""

import os
import re
from typing import Any

def generate_pytest_test(scenario: dict[str, Any], target_url: str) -> str:
    """
    Render a clean, standalone pytest-playwright test from a scenario.
    """
    scenario_id = scenario.get("id", "sc_0")
    safe_name = re.sub(r"[^a-zA-Z0-9_]", "_", scenario_id)

    lines = [
        '"""',
        f'Generated by DRISHTI AI for scenario: {scenario_id}',
        f'Journey: {scenario.get("journey", "")}',
        '"""',
        '',
        'import re',
        'import pytest',
        'from playwright.sync_api import Page, expect',
        '',
        f'def test_{safe_name}(page: Page):',
    ]

    for step in scenario.get("steps", []):
        action = step.get("action")
        target = step.get("target") or step.get("ref", "")
        value = step.get("value")

        if action == "goto":
            url = target if target.startswith("http") else f"{target_url}{target}"
            lines.append(f'    page.goto("{url}")')
        elif action == "click":
            lines.append(f'    page.click("{target}")')
        elif action == "fill":
            lines.append(f'    page.fill("{target}", "{value or ""}")')
        elif action == "press":
            lines.append(f'    page.press("{target}", "{value or "Enter"}")')
        elif action == "wait_for":
            lines.append(f'    page.wait_for_selector("{target}")')

    # Add assertions
    for a in scenario.get("assertions", []):
        atype = a.get("type")
        args = a.get("args", {})
        if atype == "url_matches":
            pat = args.get("pattern", "")
            lines.append(f'    expect(page).to_have_url(re.compile(r"{pat}"))')
        elif atype == "element_visible":
            if args.get("selector"):
                lines.append(f'    expect(page.locator("{args.get("selector")}")).to_be_visible()')
            elif args.get("text"):
                lines.append(f'    expect(page.get_by_text("{args.get("text")}")).to_be_visible()')
        elif atype == "element_absent":
            if args.get("text"):
                lines.append(f'    expect(page.get_by_text("{args.get("text")}")).not_to_be_visible()')

    lines.append("")
    return "\n".join(lines)
